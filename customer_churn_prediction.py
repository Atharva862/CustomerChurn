import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv('/content/WA_Fn-UseC_-Telco-Customer-Churn.csv')
print(df.head())

#Converting to values to numeric since they are stored as string
df['TotalCharges'] = pd.to_numeric(df['TotalCharges'], errors='coerce')

#Finding out the Total Null Values in TotalCharges
print('Null Values:', df['TotalCharges'].isnull().sum())

#Filling the null values using median values
df['TotalCharges'].fillna(df['TotalCharges'].median(), inplace=True)

#Target encoding
df['Churn'] = df['Churn'].map({'Yes':1, 'No':0})

#Replacing redundant categories
df.replace({'No internet service':'No', 'No phone service':'No'}, inplace=True)

df2 = df.drop(['customerID'], axis=1)
print(df2.head())

#Defining X and Y variables
x = df[['Contract', 'MonthlyCharges', 'InternetService', 'tenure', 'PaymentMethod']]
y = df['Churn']

#One-Hot Encoding
x = pd.get_dummies(x, drop_first=True)

#Splitting the data into train and test data

from sklearn.model_selection import train_test_split

x_train, x_test, y_train, y_test = train_test_split(x, y, test_size = 0.30, random_state = 42)

#Decision Tree model

from sklearn.tree import DecisionTreeClassifier

model = DecisionTreeClassifier()
model.fit(x_train, y_train)

#Predictions
y_pred = model.predict(x_test)

from sklearn.metrics import accuracy_score, classification_report, ConfusionMatrixDisplay

accuracy = accuracy_score(y_test, y_pred)
print('Accuracy:', accuracy)
report = classification_report(y_test, y_pred)
print('Classification Report:\n', report)

"""**Conclusion: The model achieves 72% accuracy but performs poorly on churn prediction, with recall of only 47%. This indicates that many churn customers are missed, making the model less useful for retention strategies.**"""

ConfusionMatrixDisplay.from_predictions(y_test, y_pred)
plt.show()

"""**The model works well for predicting non-churn customers, but it fails to identify many customers who actually leave. This makes it less useful for preventing churn, since many risky customers are not detected.**"""

#Important Features

importance = pd.DataFrame({
    'Feature': x.columns,
    'Importance': model.feature_importances_
}).sort_values(by='Importance', ascending=False)

print("\nTop Features:\n", importance.head(10))

"""**Overall, customers with high bills, shorter duration, and certain service/payment types are more likely to churn.**"""

from sklearn import tree

tree.plot_tree(model, feature_names = x.columns, class_names = ['Yes', 'No'])
plt.show()